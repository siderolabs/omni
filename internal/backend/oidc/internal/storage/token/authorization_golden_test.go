package token_test

import (
	"slices"
	"strings"
	"testing"

	"github.com/cosi-project/runtime/pkg/state"
	"github.com/cosi-project/runtime/pkg/state/impl/inmem"
	"github.com/stretchr/testify/require"
	"github.com/zitadel/oidc/v3/pkg/oidc"

	"github.com/siderolabs/omni/internal/backend/oidc/external"
	"github.com/siderolabs/omni/internal/backend/oidc/internal/storage/token"
	"github.com/siderolabs/omni/internal/pkg/authz/authztest"
)

const goldenHeader = `The Kubernetes groups %s gets in the token for a cluster.
%s

Generated by TestAuthorizationGolden. Rewrite with:

  go test ./internal/backend/oidc/internal/storage/token -run TestAuthorizationGolden -update

Omni issues the token which kubectl sends to the Kubernetes API proxy of Omni. The proxy impersonates the user with the
groups in the token, and refuses a token with no groups. So the groups decide who reaches the Kubernetes API of a cluster,
and as what.

Every user who is logged in gets a token, this check is not recorded here. The anonymous subject is "no token" without a call.

The groups come from the user and the access policy in the state. Whether the instance is suspended is not looked at,
so a subject on a suspended instance gets the same groups.`

// TestAuthorizationGolden records the Kubernetes groups every subject gets in a token for a cluster,
// and fails on any difference from the golden files.
func TestAuthorizationGolden(t *testing.T) {
	keys := authztest.GenerateKeys(t)
	st := state.WrapCore(inmem.NewState())

	authztest.Seed(t, st, keys)

	storage := token.NewStorage(st)

	clusters := []struct {
		name string
		id   string
	}{
		{authztest.ClusterA, authztest.ClusterA},
		{authztest.ClusterB, authztest.ClusterB},
		{"a cluster which does not exist", "missing"},
	}

	authztest.CompareGolden(t, goldenHeader, func(subject authztest.Subject, outcomes *authztest.Outcomes) {
		for _, cluster := range clusters {
			// a token is issued only to a user who logged in
			if !subject.SignedIn() {
				outcomes.Add(cluster.name, "no token")

				continue
			}

			// the claims of the ID token, which is the token kubectl sends
			userInfo := &oidc.UserInfo{}

			require.NoError(t, storage.SetUserinfoFromScopes(t.Context(), userInfo, subject.Identity(), "", []string{external.ScopeClusterPrefix + cluster.id}))

			groups, ok := userInfo.Claims["groups"].([]string)
			require.True(t, ok)

			slices.Sort(groups)

			if len(groups) == 0 {
				groups = []string{"no groups"}
			}

			outcomes.Add(cluster.name, strings.Join(groups, ", "))
		}
	})
}
