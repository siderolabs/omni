package kubernetes_test

import (
	"testing"

	"github.com/cosi-project/runtime/pkg/state"
	"github.com/cosi-project/runtime/pkg/state/impl/inmem"

	"github.com/siderolabs/omni/internal/backend/runtime/kubernetes"
	"github.com/siderolabs/omni/internal/pkg/authz/authztest"
)

const authorizationGoldenHeader = `What %s can read of the Kubernetes resources through Omni.
%s

Generated by TestAuthorizationGolden. Rewrite with:

  go test ./internal/backend/runtime/kubernetes -run TestAuthorizationGolden -update

The Kubernetes runtime serves the resources of the Kubernetes API of a cluster read-only, e.g., the nodes and the pods
which the UI shows. A call is "unauthenticated" or "denied" when the access check refused it, and "allowed" when the check
let it through.`

// TestAuthorizationGolden records which subjects can read the Kubernetes resources of a cluster through Omni,
// and fails on any difference from the golden files.
func TestAuthorizationGolden(t *testing.T) {
	keys := authztest.GenerateKeys(t)
	st := state.WrapCore(inmem.NewState())

	authztest.Seed(t, st, keys)

	authztest.CompareGolden(t, authorizationGoldenHeader, func(subject authztest.Subject, outcomes *authztest.Outcomes) {
		ctx := authztest.SignIn(t, st, keys, subject)

		for _, cluster := range []string{authztest.ClusterA, authztest.ClusterB} {
			outcomes.Add(cluster, authztest.Outcome(t, kubernetes.CheckAccess(ctx, st, cluster)))
		}
	})
}
