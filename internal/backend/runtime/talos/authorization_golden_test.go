package talos_test

import (
	"testing"

	"github.com/cosi-project/runtime/pkg/state"
	"github.com/cosi-project/runtime/pkg/state/impl/inmem"
	"github.com/stretchr/testify/require"

	"github.com/siderolabs/omni/client/pkg/omni/resources/omni"
	"github.com/siderolabs/omni/internal/backend/runtime/talos"
	"github.com/siderolabs/omni/internal/pkg/auth/actor"
	"github.com/siderolabs/omni/internal/pkg/authz/authztest"
)

const goldenHeader = `What %s can read of the Talos resources through Omni.
%s

Generated by TestAuthorizationGolden. Rewrite with:

  go test ./internal/backend/runtime/talos -run TestAuthorizationGolden -update

The Talos runtime serves the resources of Talos read-only, for a cluster or for a single machine. A call is
"unauthenticated" or "denied" when the access check refused it, and "allowed" when the check let it through.`

// TestAuthorizationGolden records which subjects can read the Talos resources of a cluster or a machine,
// and fails on any difference from the golden files.
func TestAuthorizationGolden(t *testing.T) {
	keys := authztest.GenerateKeys(t)
	st := state.WrapCore(inmem.NewState())

	authztest.Seed(t, st, keys)

	// the runtime finds the cluster of a machine in its status
	for machineID, cluster := range map[string]string{
		authztest.MemberMachine: authztest.ClusterA,
		authztest.OtherMachine:  authztest.ClusterB,
		authztest.FreeMachine:   "",
	} {
		machineStatus := omni.NewMachineStatus(machineID)
		machineStatus.TypedSpec().Value.Cluster = cluster

		require.NoError(t, st.Create(actor.MarkContextAsInternalActor(t.Context()), machineStatus))
	}

	targets := []struct {
		name    string
		cluster string
		machine string
	}{
		{name: authztest.ClusterA, cluster: authztest.ClusterA},
		{name: authztest.ClusterB, cluster: authztest.ClusterB},
		{name: "a machine in cluster-a", machine: authztest.MemberMachine},
		{name: "a machine in cluster-b", machine: authztest.OtherMachine},
		{name: "a machine in no cluster", machine: authztest.FreeMachine},
	}

	authztest.CompareGolden(t, goldenHeader, func(subject authztest.Subject, outcomes *authztest.Outcomes) {
		ctx := authztest.SignIn(t, st, keys, subject)

		for _, target := range targets {
			outcomes.Add(target.name, authztest.Outcome(t, talos.Authorize(ctx, st, target.cluster, target.machine)))
		}
	})
}
