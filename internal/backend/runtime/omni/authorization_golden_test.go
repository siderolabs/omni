// TestAuthorizationGolden records what every subject gets back for every verb on every registered resource type,
// and fails on any difference from the golden file.
func TestAuthorizationGolden(t *testing.T) {
	keys := subjectKeys(t)

	// the COSI meta types are registered separately from the Omni ones
	definitions := append(slices.Clone(registry.Resources), &meta.Namespace{}, &meta.ResourceDefinition{})

	var resourceRows [][]string

	kindRows := make([][]string, 0, len(kindQueries)*len(definitions))

	for _, def := range definitions {
		rd := def.ResourceDefinition()

		if rd.DefaultNamespace == resources.VirtualNamespace {
			require.Contains(t, virtualIDs, rd.Type, "add the ID the virtual state serves to virtualIDs")
		}

		w := newWorld(t, keys)
		contexts := w.subjectContexts(t)

		for _, tgt := range targetsFor(rd.Type, rd.DefaultNamespace) {
			row := append(make([]string, 0, 2+len(contexts)), rd.Type, tgt.name)

			for _, ctx := range contexts {
				row = append(row, w.resourceCell(t, ctx, rd.Type, rd.DefaultNamespace, tgt))
			}

			resourceRows = append(resourceRows, row)
		}

		for _, kq := range kindQueries {
			row := append(make([]string, 0, 2+len(contexts)), rd.Type, kq.name)

			for _, ctx := range contexts {
				row = append(row, w.kindCell(ctx, resource.NewMetadata(rd.DefaultNamespace, rd.Type, "", resource.VersionUndefined), kq.queries))
			}

			kindRows = append(kindRows, row)
		}
	}

	w := newWorld(t, keys)
	contexts := w.subjectContexts(t)

	var buf bytes.Buffer

	buf.WriteString(goldenHeader)

	writeSection(t, &buf, "Resources: verbs get, watch, create, update, destroy", []string{"type", "target"}, resourceRows)
	writeSection(t, &buf, "Kinds: verbs list, watch kind", []string{"type", "query"}, kindRows)
	writeSection(t, &buf, "UI permission flags: + set, - unset", []string{"resource", "flag"}, w.flagRows(t, contexts))

	compareGolden(t, filepath.Join("testdata", "authorization.txt"), buf.Bytes())
}

func targetsFor(typ resource.Type, ns resource.Namespace) []target {
	switch ns {
	case resources.VirtualNamespace:
		targets := make([]target, 0, len(virtualIDs[typ])+1)

		for _, id := range virtualIDs[typ] {
			targets = append(targets, target{name: id, id: id})
		}

		return append(targets, target{name: "absent", id: "absent", absent: true})
	case resources.ExternalNamespace:
		// read from the etcd backup store of the cluster, the ID is the cluster ID and the backup time
		return []target{{name: "absent", id: clusterA + "-1700000000", absent: true}}
	}

	if infraprovider.IsInfraProviderNamespace(ns) {
		return providerTargets
	}

	if typ == siderolink.LinkStatusType {
		return linkStatusTargets()
	}

	return clusterTargets
}

// linkStatusTargets are the targets of LinkStatus, whose ID contains the type of the resource it is the status of.
func linkStatusTargets() []target {
	targets := slices.Clone(clusterTargets)

	for i := range targets {
		targets[i].id = siderolink.LinkStatusID(targets[i].id, siderolink.LinkType)
	}

	// a machine which is not accepted yet can have the ID of a machine in a cluster
	return append(targets, target{name: "member-machine pending", id: siderolink.LinkStatusID("machine-a", siderolink.PendingMachineType)})
}

type subjectKey struct {
	fingerprint string
	pem         []byte
}

func subjectKeys(t *testing.T) map[string]subjectKey {
	keys := map[string]subjectKey{}

	for _, s := range subjects {
		if !s.signedIn() {
			continue
		}

		privateKey, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
		require.NoError(t, err)

		der, err := x509.MarshalPKIXPublicKey(&privateKey.PublicKey)
		require.NoError(t, err)

		keyPEM := pem.EncodeToMemory(&pem.Block{Type: "PUBLIC KEY", Bytes: der})

		key, err := plain.ParseKey(keyPEM)
		require.NoError(t, err)

		keys[s.name] = subjectKey{pem: keyPEM, fingerprint: key.ID()}
	}

	return keys
}

// world is a fresh state with the subjects, the access policy and the infra providers in it.
type world struct {
	authorized   state.State
	unauthorized state.State
	keys         map[string]subjectKey
}

func newWorld(t *testing.T, keys map[string]subjectKey) *world {
	authorized, unauthorized, err := omniruntime.NewAuthorizedState("https://omni.example.org")
	require.NoError(t, err)

	w := &world{authorized: authorized, unauthorized: unauthorized, keys: keys}
	ctx := actor.MarkContextAsInternalActor(t.Context())

	policy := testAccessPolicy()
	require.NoError(t, accesspolicy.Validate(policy))

	fixtures := []resource.Resource{policy, infra.NewProvider(ownProvider), infra.NewProvider(otherProvider)}

	for _, s := range subjects {
		if !s.signedIn() {
			continue
		}

		user := authres.NewUser(s.name)
		user.TypedSpec().Value.Role = string(s.role)

		identity := authres.NewIdentity(s.identity())
		identity.TypedSpec().Value.UserId = s.name

		for k, v := range s.labels {
			identity.Metadata().Labels().Set(k, v)
		}

		key := authres.NewPublicKey(keys[s.name].fingerprint)
		key.Metadata().Labels().Set(authres.LabelPublicKeyUserID, s.name)
		key.TypedSpec().Value.PublicKey = keys[s.name].pem
		key.TypedSpec().Value.Type = specs.PublicKeySpec_PLAIN
		key.TypedSpec().Value.Confirmed = true //nolint:staticcheck
		key.TypedSpec().Value.Expiration = timestamppb.New(time.Now().Add(time.Hour))
		key.TypedSpec().Value.Identity = &specs.Identity{Email: s.identity()}

		fixtures = append(fixtures, user, identity, key)
	}

	// machine-a is a member of cluster-a
	clusterMachine := omni.NewClusterMachine("machine-a")
	clusterMachine.Metadata().Labels().Set(omni.LabelCluster, clusterA)

	fixtures = append(fixtures, clusterMachine)

	for _, res := range fixtures {
		require.NoError(t, w.unauthorized.Create(ctx, res))
	}

	return w
}

// subjectContexts signs every subject in through the production authenticator, in the order of subjects.
func (w *world) subjectContexts(t *testing.T) []context.Context {
	contexts := make([]context.Context, 0, len(subjects))

	for _, s := range subjects {
		if !s.signedIn() {
			contexts = append(contexts, t.Context())

			continue
		}

		fingerprint := w.keys[s.name].fingerprint

		authn, err := authenticator.New(w.unauthorized, s.suspended)(t.Context(), fingerprint)
		require.NoError(t, err)

		contexts = append(contexts, auth.ContextWithAuthenticator(t.Context(), authn, fingerprint))
	}

	return contexts
}

func newResource(t *testing.T, typ resource.Type, ns resource.Namespace, tgt target) resource.Resource {
	res, err := protobuf.CreateResource(typ)
	require.NoError(t, err)

	md := resource.NewMetadata(ns, typ, tgt.id, resource.VersionUndefined)

	unmarshaler, ok := res.(protobuf.ResourceUnmarshaler)
	require.True(t, ok)
	require.NoError(t, unmarshaler.UnmarshalProto(&md, nil))

	for k, v := range tgt.labels {
		res.Metadata().Labels().Set(k, v)
	}

	// admins register the providers, so a provider never has its own ID label
	if typ == infra.ProviderType {
		res.Metadata().Labels().Delete(omni.LabelInfraProviderID)
	}

	// the infra provider state validates this spec on every write
	if request, isRequest := res.(*infra.MachineRequest); isRequest {
		request.TypedSpec().Value.TalosVersion = constants.DefaultTalosVersion
	}

	return res
}

// reset puts the target back to its initial state: present with its labels, or absent.
// The virtual and the external states serve resources they compute or read from elsewhere, so there is nothing to reset.
func (w *world) reset(ctx context.Context, t *testing.T, res resource.Resource, present bool) {
	if ns := res.Metadata().Namespace(); ns == resources.VirtualNamespace || ns == resources.ExternalNamespace {
		return
	}

	if err := w.unauthorized.Destroy(ctx, res.Metadata()); err != nil && !state.IsNotFoundError(err) {
		require.NoError(t, err)
	}

	if present {
		require.NoError(t, w.unauthorized.Create(ctx, res.DeepCopy()))
	}
}

func (w *world) resourceCell(t *testing.T, ctx context.Context, typ resource.Type, ns resource.Namespace, tgt target) string {
	if tgt.namespace != "" {
		ns = tgt.namespace
	}

	res := newResource(t, typ, ns, tgt)
	ptr := res.Metadata()
	present := !tgt.absent
	internalCtx := actor.MarkContextAsInternalActor(ctx)

	defer w.reset(internalCtx, t, res, present)

	call := func(letter byte, verb func() error) byte {
		w.reset(internalCtx, t, res, present)

		return outcome(letter, verb())
	}

	update := func() error {
		updated := res.DeepCopy()

		if present && ns != resources.VirtualNamespace && ns != resources.ExternalNamespace {
			current, err := w.unauthorized.Get(internalCtx, ptr)
			require.NoError(t, err)

			updated = current.DeepCopy()
		}

		updated.Metadata().Annotations().Set("updated", "true")

		if tgt.relabel != "" {
			updated.Metadata().Labels().Set(omni.LabelCluster, tgt.relabel)
		}

		return w.authorized.Update(ctx, updated)
	}

	if tgt.relabel != "" {
		return "___" + string(call('u', update)) + "_"
	}

	cell := []byte{
		call('g', func() error {
			_, err := w.authorized.Get(ctx, ptr)

			return err
		}),
		call('w', func() error {
			watchCtx, cancel := context.WithCancel(ctx)
			defer cancel()

			return w.authorized.Watch(watchCtx, ptr, make(chan state.Event, 16))
		}),
		'_',
		call('u', update),
		call('d', func() error {
			return w.authorized.Destroy(ctx, ptr)
		}),
	}

	w.reset(internalCtx, t, res, false)

	cell[2] = outcome('c', w.authorized.Create(ctx, res.DeepCopy()))

	return string(cell)
}

func (w *world) kindCell(ctx context.Context, kind resource.Kind, queries [][]resource.LabelQueryOption) string {
	listOpts := make([]state.ListOption, 0, len(queries))
	watchOpts := make([]state.WatchKindOption, 0, len(queries))

	for _, q := range queries {
		listOpts = append(listOpts, state.WithLabelQuery(q...))
		watchOpts = append(watchOpts, state.WatchWithLabelQuery(q...))
	}

	_, listErr := w.authorized.List(ctx, kind, listOpts...)

	watchCtx, cancel := context.WithCancel(ctx)
	defer cancel()

	watchErr := w.authorized.WatchKind(watchCtx, kind, make(chan state.Event, 16), watchOpts...)

	return string([]byte{outcome('l', listErr), outcome('w', watchErr)})
}

// flagRows reads the permission flags the UI shows or hides controls by.
func (w *world) flagRows(t *testing.T, contexts []context.Context) [][]string {
	var rows [][]string

	addRows := func(name string, desc protoreflect.MessageDescriptor, get func(ctx context.Context) (protoreflect.Message, error)) {
		msgs := make([]protoreflect.Message, 0, len(contexts))
		errs := make([]error, 0, len(contexts))

		for _, ctx := range contexts {
			msg, err := get(ctx)

			msgs = append(msgs, msg)
			errs = append(errs, err)
		}

		for i := range desc.Fields().Len() {
			field := desc.Fields().Get(i)
			row := []string{name, string(field.Name())}

			for j, msg := range msgs {
				switch {
				case errs[j] != nil:
					row = append(row, string(outcome(0, errs[j])))
				case msg.Get(field).Bool():
					row = append(row, "+")
				default:
					row = append(row, "-")
				}
			}

			rows = append(rows, row)
		}
	}

	addRows(virtual.PermissionsType, (&specs.PermissionsSpec{}).ProtoReflect().Descriptor(), func(ctx context.Context) (protoreflect.Message, error) {
		res, err := safe.StateGetByID[*virtual.Permissions](ctx, w.authorized, virtual.PermissionsID)
		if err != nil {
			return nil, err
		}

		return res.TypedSpec().Value.ProtoReflect(), nil
	})

	for _, cluster := range []string{clusterA, clusterB} {
		addRows(virtual.ClusterPermissionsType+" "+cluster, (&specs.ClusterPermissionsSpec{}).ProtoReflect().Descriptor(), func(ctx context.Context) (protoreflect.Message, error) {
			res, err := safe.StateGetByID[*virtual.ClusterPermissions](ctx, w.authorized, cluster)
			if err != nil {
				return nil, err
			}

			return res.TypedSpec().Value.ProtoReflect(), nil
		})
	}

	require.NotEmpty(t, rows)

	return rows
}

func outcome(letter byte, err error) byte {
	switch {
	case err == nil:
		return letter
	case state.IsNotFoundError(err), status.Code(err) == codes.NotFound:
		return 'n'
	case state.IsUnsupportedError(err):
		return 'x'
	case status.Code(err) == codes.PermissionDenied:
		return '.'
	case status.Code(err) == codes.Unauthenticated:
		return '?'
	case status.Code(err) == codes.InvalidArgument:
		return '!'
	default:
		return 'E'
	}
}

func writeSection(t *testing.T, buf *bytes.Buffer, title string, keyColumns []string, rows [][]string) {
	buf.WriteString("\n# " + title + "\n\n")

	slices.SortStableFunc(rows, func(a, b []string) int {
		return strings.Compare(a[0], b[0])
	})

	tw := tabwriter.NewWriter(buf, 0, 0, 2, ' ', tabwriter.DiscardEmptyColumns)

	header := slices.Clone(keyColumns)

	for _, s := range subjects {
		header = append(header, s.name)
	}

	for _, row := range append([][]string{header}, rows...) {
		_, err := tw.Write([]byte(strings.Join(row, "\t") + "\n"))
		require.NoError(t, err)
	}

	require.NoError(t, tw.Flush())
}

func compareGolden(t *testing.T, path string, actual []byte) {
	if *updateGolden {
		require.NoError(t, os.MkdirAll(filepath.Dir(path), 0o755))
		require.NoError(t, os.WriteFile(path, actual, 0o644))

		return
	}

	expected, err := os.ReadFile(path)
	require.NoError(t, err, "golden file is missing, create it with -update")

	require.Equal(t, string(expected), string(actual), "authorization changed, review the diff and rewrite the golden file with -update")
}
