const goldenHeader = `What %s can do through the resource API.
%s

Generated by TestAuthorizationGolden. Rewrite with:

  go test ./internal/backend/runtime/omni -run TestAuthorizationGolden -update

Every call goes through the production state composition with only the authorization checks on top,
so the file shows what the caller gets back, not only whether the check passed.

The resource types which behave the same for this subject are listed together.`

// target is a resource the subjects act on. The types get the same targets, with a few exceptions in targetsFor,
// so the rows do not depend on how the authorization code classifies a type.
type target struct {
	labels map[string]string
	// situation says in the golden file which resource the calls are for, e.g., "a resource in cluster-a".
	situation string
	namespace resource.Namespace // overrides the default namespace of the type
	id        resource.ID
	relabel   string // when set, the row is an update moving the resource from its cluster to this one
	absent    bool
}

