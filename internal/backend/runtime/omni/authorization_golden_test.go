// TestAuthorizationGolden records what every subject gets back for every verb on every registered resource type,
// and fails on any difference from the golden files.
//
// There is a golden file for each subject. The resource types which behave the same for the subject are listed together,
// followed by the situations the calls are made in, e.g., "a resource in cluster-a", and the verbs under their outcome.
func TestAuthorizationGolden(t *testing.T) {
	keys := subjectKeys(t)

	// the COSI meta types are registered separately from the Omni ones
	definitions := append(slices.Clone(registry.Resources), &meta.Namespace{}, &meta.ResourceDefinition{})

	slices.SortStableFunc(definitions, func(a, b meta.ResourceWithRD) int {
		return strings.Compare(a.ResourceDefinition().Type, b.ResourceDefinition().Type)
	})

	// what each subject gets back for each type, in the order of subjects
	behaviors := make([][]typeBehavior, len(subjects))

	for _, def := range definitions {
		rd := def.ResourceDefinition()

		if rd.DefaultNamespace == resources.VirtualNamespace {
			require.Contains(t, virtualIDs, rd.Type, "add the ID the virtual state serves to virtualIDs")
		}

		w := newWorld(t, keys)

		for i, ctx := range w.subjectContexts(t) {
			behavior := typeBehavior{typ: rd.Type}

			for _, tgt := range targetsFor(rd.Type, rd.DefaultNamespace) {
				behavior.situations = append(behavior.situations, situation{name: tgt.situation, results: w.resourceResults(t, ctx, rd.Type, rd.DefaultNamespace, tgt)})
			}

			for _, kq := range kindQueries {
				kind := resource.NewMetadata(rd.DefaultNamespace, rd.Type, "", resource.VersionUndefined)

				behavior.situations = append(behavior.situations, situation{name: kq.situation, results: w.kindResults(ctx, kind, kq.queries)})
			}

			behaviors[i] = append(behaviors[i], behavior)
		}
	}

	w := newWorld(t, keys)
	files := make(map[string][]byte, len(subjects))

	for i, ctx := range w.subjectContexts(t) {
		s := subjects[i]

		files[s.name+".yaml"] = goldenFile(t, fmt.Sprintf(goldenHeader, s.name, s.description), behaviors[i], w.flags(t, ctx))
	}

	compareGoldenFiles(t, filepath.Join("testdata", "authorization"), files)
}

// result is a call to the resource API and what the subject got back from it.
type result struct {
	verb    string
	outcome string
}

// situation is what a group of calls is made on, e.g., "a resource in cluster-a", and their results.
type situation struct {
	name    string
	results []result
}

// typeBehavior is what a subject gets back for a resource type, in every situation.
type typeBehavior struct {
	typ        resource.Type
	situations []situation
}

// outcomes are the outcomes of a call, in the order they are written in the golden files.
var outcomes = []string{"allowed", "denied", "unauthenticated", "not-found", "unsupported", "invalid-argument", "error"}

// goldenFile returns the golden file of a subject.
func goldenFile(t *testing.T, header string, behaviors []typeBehavior, flags *yaml.Node) []byte {
	scalar := func(value string) *yaml.Node {
		return &yaml.Node{Kind: yaml.ScalarNode, Value: value}
	}

	// the situations of a type as a list of cases, each with the verbs under their outcome
	situations := func(behavior typeBehavior) *yaml.Node {
		node := &yaml.Node{Kind: yaml.SequenceNode}

		for _, sit := range behavior.situations {
			byOutcome := &yaml.Node{Kind: yaml.MappingNode, Content: []*yaml.Node{scalar("case"), scalar(sit.name)}}

			for _, outcome := range outcomes {
				verbs := &yaml.Node{Kind: yaml.SequenceNode, Style: yaml.FlowStyle}

				for _, res := range sit.results {
					if res.outcome == outcome {
						verbs.Content = append(verbs.Content, scalar(res.verb))
					}
				}

				if len(verbs.Content) > 0 {
					byOutcome.Content = append(byOutcome.Content, scalar(outcome), verbs)
				}
			}

			node.Content = append(node.Content, byOutcome)
		}

		return node
	}

	// the types which behave the same share a block, the blocks are in the order of their first type
	var (
		blocks  []*yaml.Node
		blockOf = map[string]*yaml.Node{}
	)

	for _, behavior := range behaviors {
		node := situations(behavior)

		encoded, err := yaml.Marshal(node)
		require.NoError(t, err)

		block, ok := blockOf[string(encoded)]
		if !ok {
			block = &yaml.Node{Kind: yaml.MappingNode, Content: []*yaml.Node{scalar("types"), {Kind: yaml.SequenceNode}, scalar("cases"), node}}

			blockOf[string(encoded)] = block
			blocks = append(blocks, block)
		}

		block.Content[1].Content = append(block.Content[1].Content, scalar(behavior.typ))
	}

	root := &yaml.Node{
		Kind:        yaml.MappingNode,
		HeadComment: header,
		Content: []*yaml.Node{
			scalar("resources"),
			{Kind: yaml.SequenceNode, Content: blocks},
			scalar("flags"), flags,
		},
	}

	var buf bytes.Buffer

	encoder := yaml.NewEncoder(&buf)
	encoder.SetIndent(2)

	require.NoError(t, encoder.Encode(root))
	require.NoError(t, encoder.Close())

	// an empty line between the blocks, for the reader
	content := bytes.ReplaceAll(buf.Bytes(), []byte("\n  - types:"), []byte("\n\n  - types:"))
	content = bytes.Replace(content, []byte("\nresources:\n\n"), []byte("\nresources:\n"), 1)

	return bytes.Replace(content, []byte("\nflags:"), []byte("\n\nflags:"), 1)
}

func targetsFor(typ resource.Type, ns resource.Namespace) []target {
	switch ns {
	case resources.VirtualNamespace:
		targets := make([]target, 0, len(virtualIDs[typ])+1)

		for _, id := range virtualIDs[typ] {
			targets = append(targets, target{situation: "the resource " + strconv.Quote(id), id: id})
		}

		return append(targets, target{situation: "a resource which does not exist", id: "absent", absent: true})
	case resources.ExternalNamespace:
		// read from the etcd backup store of the cluster, the ID is the cluster ID and the backup time
		return []target{{situation: "a resource which does not exist", id: clusterA + "-1700000000", absent: true}}
	}

	if infraprovider.IsInfraProviderNamespace(ns) {
		return providerTargets
	}

	if typ == siderolink.LinkStatusType {
		return linkStatusTargets()
	}

	return clusterTargets
}

// linkStatusTargets are the targets of LinkStatus, whose ID contains the type of the resource it is the status of.
func linkStatusTargets() []target {
	targets := slices.Clone(clusterTargets)

	for i := range targets {
		targets[i].id = siderolink.LinkStatusID(targets[i].id, siderolink.LinkType)
	}

	// a machine which is not accepted yet can have the ID of a machine in a cluster
	return append(targets, target{
		situation: "a resource of a pending machine with the ID of a machine in cluster-a",
		id:        siderolink.LinkStatusID("machine-a", siderolink.PendingMachineType),
	})
}

type subjectKey struct {
	fingerprint string
	pem         []byte
}

func subjectKeys(t *testing.T) map[string]subjectKey {
	keys := map[string]subjectKey{}

	for _, s := range subjects {
		if !s.signedIn() {
			continue
		}

		privateKey, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
		require.NoError(t, err)

		der, err := x509.MarshalPKIXPublicKey(&privateKey.PublicKey)
		require.NoError(t, err)

		keyPEM := pem.EncodeToMemory(&pem.Block{Type: "PUBLIC KEY", Bytes: der})

		key, err := plain.ParseKey(keyPEM)
		require.NoError(t, err)

		keys[s.name] = subjectKey{pem: keyPEM, fingerprint: key.ID()}
	}

	return keys
}

// world is a fresh state with the subjects, the access policy and the infra providers in it.
type world struct {
	authorized   state.State
	unauthorized state.State
	keys         map[string]subjectKey
}

func newWorld(t *testing.T, keys map[string]subjectKey) *world {
	authorized, unauthorized, err := omniruntime.NewAuthorizedState("https://omni.example.org")
	require.NoError(t, err)

	w := &world{authorized: authorized, unauthorized: unauthorized, keys: keys}
	ctx := actor.MarkContextAsInternalActor(t.Context())

	policy := testAccessPolicy()
	require.NoError(t, accesspolicy.Validate(policy))

	fixtures := []resource.Resource{policy, infra.NewProvider(ownProvider), infra.NewProvider(otherProvider)}

	for _, s := range subjects {
		if !s.signedIn() {
			continue
		}

		user := authres.NewUser(s.name)
		user.TypedSpec().Value.Role = string(s.role)

		identity := authres.NewIdentity(s.identity())
		identity.TypedSpec().Value.UserId = s.name

		for k, v := range s.labels {
			identity.Metadata().Labels().Set(k, v)
		}

		key := authres.NewPublicKey(keys[s.name].fingerprint)
		key.Metadata().Labels().Set(authres.LabelPublicKeyUserID, s.name)
		key.TypedSpec().Value.PublicKey = keys[s.name].pem
		key.TypedSpec().Value.Type = specs.PublicKeySpec_PLAIN
		key.TypedSpec().Value.Confirmed = true //nolint:staticcheck
		key.TypedSpec().Value.Expiration = timestamppb.New(time.Now().Add(time.Hour))
		key.TypedSpec().Value.Identity = &specs.Identity{Email: s.identity()}

		fixtures = append(fixtures, user, identity, key)
	}

	// machine-a is a member of cluster-a
	clusterMachine := omni.NewClusterMachine("machine-a")
	clusterMachine.Metadata().Labels().Set(omni.LabelCluster, clusterA)

	fixtures = append(fixtures, clusterMachine)

	for _, res := range fixtures {
		require.NoError(t, w.unauthorized.Create(ctx, res))
	}

	return w
}

// subjectContexts signs every subject in through the production authenticator, in the order of subjects.
func (w *world) subjectContexts(t *testing.T) []context.Context {
	contexts := make([]context.Context, 0, len(subjects))

	for _, s := range subjects {
		if !s.signedIn() {
			contexts = append(contexts, t.Context())

			continue
		}

		fingerprint := w.keys[s.name].fingerprint

		authn, err := authenticator.New(w.unauthorized, s.suspended)(t.Context(), fingerprint)
		require.NoError(t, err)

		contexts = append(contexts, auth.ContextWithAuthenticator(t.Context(), authn, fingerprint))
	}

	return contexts
}

func newResource(t *testing.T, typ resource.Type, ns resource.Namespace, tgt target) resource.Resource {
	res, err := protobuf.CreateResource(typ)
	require.NoError(t, err)

	md := resource.NewMetadata(ns, typ, tgt.id, resource.VersionUndefined)

	unmarshaler, ok := res.(protobuf.ResourceUnmarshaler)
	require.True(t, ok)
	require.NoError(t, unmarshaler.UnmarshalProto(&md, nil))

	for k, v := range tgt.labels {
		res.Metadata().Labels().Set(k, v)
	}

	// admins register the providers, so a provider never has its own ID label
	if typ == infra.ProviderType {
		res.Metadata().Labels().Delete(omni.LabelInfraProviderID)
	}

	// the infra provider state validates this spec on every write
	if request, isRequest := res.(*infra.MachineRequest); isRequest {
		request.TypedSpec().Value.TalosVersion = constants.DefaultTalosVersion
	}

	return res
}

// reset puts the target back to its initial state: present with its labels, or absent.
// The virtual and the external states serve resources they compute or read from elsewhere, so there is nothing to reset.
func (w *world) reset(ctx context.Context, t *testing.T, res resource.Resource, present bool) {
	if ns := res.Metadata().Namespace(); ns == resources.VirtualNamespace || ns == resources.ExternalNamespace {
		return
	}

	if err := w.unauthorized.Destroy(ctx, res.Metadata()); err != nil && !state.IsNotFoundError(err) {
		require.NoError(t, err)
	}

	if present {
		require.NoError(t, w.unauthorized.Create(ctx, res.DeepCopy()))
	}
}

// resourceResults does every call on a single resource as the subject in the context.
func (w *world) resourceResults(t *testing.T, ctx context.Context, typ resource.Type, ns resource.Namespace, tgt target) []result {
	if tgt.namespace != "" {
		ns = tgt.namespace
	}

	res := newResource(t, typ, ns, tgt)
	ptr := res.Metadata()
	present := !tgt.absent
	internalCtx := actor.MarkContextAsInternalActor(ctx)

	defer w.reset(internalCtx, t, res, present)

	call := func(verb string, do func() error) result {
		w.reset(internalCtx, t, res, present)

		return result{verb: verb, outcome: outcome(do())}
	}

	update := func() error {
		updated := res.DeepCopy()

		if present && ns != resources.VirtualNamespace && ns != resources.ExternalNamespace {
			current, err := w.unauthorized.Get(internalCtx, ptr)
			require.NoError(t, err)

			updated = current.DeepCopy()
		}

		updated.Metadata().Annotations().Set("updated", "true")

		if tgt.relabel != "" {
			updated.Metadata().Labels().Set(omni.LabelCluster, tgt.relabel)
		}

		return w.authorized.Update(ctx, updated)
	}

	// moving a resource to another cluster is an update, the other verbs are not called for it
	if tgt.relabel != "" {
		return []result{call("move", update)}
	}

	get := call("get", func() error {
		_, err := w.authorized.Get(ctx, ptr)

		return err
	})

	watch := call("watch", func() error {
		watchCtx, cancel := context.WithCancel(ctx)
		defer cancel()

		return w.authorized.Watch(watchCtx, ptr, make(chan state.Event, 16))
	})

	updated := call("update", update)

	destroy := call("destroy", func() error {
		return w.authorized.Destroy(ctx, ptr)
	})

	// the create is done last, on the resource which is removed for it
	w.reset(internalCtx, t, res, false)

	create := result{verb: "create", outcome: outcome(w.authorized.Create(ctx, res.DeepCopy()))}

	return []result{get, watch, create, updated, destroy}
}

// kindResults does a list and a watch of a whole type as the subject in the context.
func (w *world) kindResults(ctx context.Context, kind resource.Kind, queries [][]resource.LabelQueryOption) []result {
	listOpts := make([]state.ListOption, 0, len(queries))
	watchOpts := make([]state.WatchKindOption, 0, len(queries))

	for _, q := range queries {
		listOpts = append(listOpts, state.WithLabelQuery(q...))
		watchOpts = append(watchOpts, state.WatchWithLabelQuery(q...))
	}

	_, listErr := w.authorized.List(ctx, kind, listOpts...)

	watchCtx, cancel := context.WithCancel(ctx)
	defer cancel()

	watchErr := w.authorized.WatchKind(watchCtx, kind, make(chan state.Event, 16), watchOpts...)

	return []result{{verb: "list", outcome: outcome(listErr)}, {verb: "watch", outcome: outcome(watchErr)}}
}

// flags reads the permission flags the UI shows or hides controls by, as the subject in the context.
//
// It returns a mapping from the resource which holds the flags to the flags and their values.
func (w *world) flags(t *testing.T, ctx context.Context) *yaml.Node {
	node := &yaml.Node{Kind: yaml.MappingNode}

	add := func(name string, desc protoreflect.MessageDescriptor, get func() (protoreflect.Message, error)) {
		msg, err := get()
		values := &yaml.Node{Kind: yaml.MappingNode}

		for i := range desc.Fields().Len() {
			field := desc.Fields().Get(i)
			value := &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!bool", Value: "false"}

			switch {
			case err != nil:
				value = &yaml.Node{Kind: yaml.ScalarNode, Value: outcome(err)}
			case msg.Get(field).Bool():
				value.Value = "true"
			}

			values.Content = append(values.Content, &yaml.Node{Kind: yaml.ScalarNode, Value: string(field.Name())}, value)
		}

		node.Content = append(node.Content, &yaml.Node{Kind: yaml.ScalarNode, Value: name}, values)
	}

	add(virtual.PermissionsType, (&specs.PermissionsSpec{}).ProtoReflect().Descriptor(), func() (protoreflect.Message, error) {
		res, err := safe.StateGetByID[*virtual.Permissions](ctx, w.authorized, virtual.PermissionsID)
		if err != nil {
			return nil, err
		}

		return res.TypedSpec().Value.ProtoReflect(), nil
	})

	for _, cluster := range []string{clusterA, clusterB} {
		add(virtual.ClusterPermissionsType+" of "+cluster, (&specs.ClusterPermissionsSpec{}).ProtoReflect().Descriptor(), func() (protoreflect.Message, error) {
			res, err := safe.StateGetByID[*virtual.ClusterPermissions](ctx, w.authorized, cluster)
			if err != nil {
				return nil, err
			}

			return res.TypedSpec().Value.ProtoReflect(), nil
		})
	}

	require.NotEmpty(t, node.Content)

	return node
}

// outcome returns what a call got back, as it is written in the golden files.
func outcome(err error) string {
	switch {
	case err == nil:
		return "allowed"
	case state.IsNotFoundError(err), status.Code(err) == codes.NotFound:
		return "not-found"
	case state.IsUnsupportedError(err):
		return "unsupported"
	case status.Code(err) == codes.PermissionDenied:
		return "denied"
	case status.Code(err) == codes.Unauthenticated:
		return "unauthenticated"
	case status.Code(err) == codes.InvalidArgument:
		return "invalid-argument"
	default:
		return "error"
	}
}

// compareGoldenFiles fails when the files differ from the golden files in the directory. With the -update flag it rewrites them.
//
// The content is compared and not the bytes, so the formatting of a golden file does not matter.
func compareGoldenFiles(t *testing.T, dir string, files map[string][]byte) {
	if *updateGolden {
		require.NoError(t, os.RemoveAll(dir))
		require.NoError(t, os.MkdirAll(dir, 0o755))

		for name, content := range files {
			require.NoError(t, os.WriteFile(filepath.Join(dir, name), content, 0o644))
		}

		return
	}

	entries, err := os.ReadDir(dir)
	require.NoError(t, err, "golden files are missing, create them with -update")

	// a file which no subject writes anymore fails the test too
	for _, entry := range entries {
		require.Contains(t, files, entry.Name(), "golden file %s has no subject, rewrite the golden files with -update", entry.Name())
	}

	for _, name := range slices.Sorted(maps.Keys(files)) {
		golden, err := os.ReadFile(filepath.Join(dir, name))
		require.NoError(t, err, "golden file %s is missing, create it with -update", name)

		var expected, actual any

		require.NoError(t, yaml.Unmarshal(golden, &expected), "golden file %s", name)
		require.NoError(t, yaml.Unmarshal(files[name], &actual))

		require.Equal(t, expected, actual, "authorization changed in %s, review the diff and rewrite the golden files with -update", name)
	}
}
