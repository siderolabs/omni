const goldenHeader = `# Generated by TestAuthorizationGolden. Rewrite with:
#
#   go test ./internal/backend/runtime/omni -run TestAuthorizationGolden -update
#
# Every call goes through the production state composition with only the authorization checks on top,
# so a cell shows what the caller gets back, not only whether the check passed.
#
# Subjects are set up the way an administrator sets them up today, a user with a role and an access policy:
#   - acl-reader-a has the role None and gets Reader on cluster-a, the user and the cluster matched by name
#   - acl-operator-a has the role Reader and gets Operator on the clusters matching *-a, matched by the identity label team=a
#   - acl-operator-all has the role None and gets Operator on every cluster, matched by a user glob
#   - suspended-admin is an Admin on a suspended instance
#   - suspended-acl-operator-a is acl-operator-a on a suspended instance
#
# Results: the verb letter when the call succeeds, "." PermissionDenied, "?" Unauthenticated, "n" NotFound,
# "x" Unsupported, "!" InvalidArgument, "E" any other error, "_" not called.
`

// subject is a caller, set up as data the way an administrator sets one up today.
type subject struct {
	labels    map[string]string
	name      string
	role      role.Role
	suspended bool
}

func (s subject) signedIn() bool {
	return s.role != ""
}

func (s subject) identity() string {
	if s.role == role.InfraProvider {
		return ownProvider + access.InfraProviderServiceAccountNameSuffix
	}

	return s.name + "@example.org"
}

const (
	clusterA      = "cluster-a"
	clusterB      = "cluster-b"
	ownProvider   = "own"
	otherProvider = "other"
)

