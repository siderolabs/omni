// TestRPCAuthorizationGolden records what every subject gets back from every RPC of the management API,
// and fails on any difference from the golden files.
//
// There is a golden file for each subject, with the RPCs in it and the outcome of each call.
func TestRPCAuthorizationGolden(t *testing.T) {
	keys := authztest.GenerateKeys(t)

	// the handlers of the RPCs, which take the request from the function they are given
	handlers := map[string]func(server *grpcomni.ManagementServer, ctx context.Context, request proto.Message) error{}

	for _, method := range management.ManagementService_ServiceDesc.Methods {
		handlers[method.MethodName] = func(server *grpcomni.ManagementServer, ctx context.Context, request proto.Message) error {
			_, err := method.Handler(server, ctx, func(decoded any) error {
				proto.Merge(decoded.(proto.Message), request) //nolint:forcetypeassert,errcheck

				return nil
			}, nil)

			return err
		}
	}

	for _, stream := range management.ManagementService_ServiceDesc.Streams {
		handlers[stream.StreamName] = func(server *grpcomni.ManagementServer, ctx context.Context, request proto.Message) error {
			return stream.Handler(server, &requestStream{ctx: ctx, request: request})
		}
	}

	sqliteConfig := config.Default().Storage.Sqlite
	sqliteConfig.SetPath(filepath.Join(t.TempDir(), "test.db"))

	db, err := sqlite.OpenDB(sqliteConfig)
	require.NoError(t, err)

	t.Cleanup(func() { require.NoError(t, db.Close()) })

	// the machine logs are read from a store which is empty here
	logHandler, err := siderolink.NewLogHandler(db, nil, state.WrapCore(inmem.NewState()), &config.Default().Logs.Machine, zap.NewNop())
	require.NoError(t, err)

	files := make(map[string][]byte, len(authztest.Subjects))

	for _, subject := range authztest.Subjects {
		rpcs := &yaml.Node{Kind: yaml.MappingNode}

		for _, name := range slices.Sorted(maps.Keys(handlers)) {
			calls, ok := rpcCalls[name]
			require.True(t, ok, "add a call for the RPC %s to rpcCalls", name)

			outcomes := &yaml.Node{Kind: yaml.MappingNode}

			for _, call := range calls {
				// a fresh state for each call, as some calls change the state. The server gets it with the access checks
				// of the resources on top, as in production.
				authorized, unauthorized, err := omniruntime.NewAuthorizedState("https://omni.example.org")
				require.NoError(t, err)

				authztest.Seed(t, unauthorized, keys)

				// a request always has metadata, and the clients send the cluster in it
				md := metadata.MD{}

				if call.cluster != "" {
					md.Set("cluster", call.cluster)
				}

				ctx := metadata.NewIncomingContext(authztest.SignIn(t, unauthorized, keys, subject), md)

				ctx, cancel := context.WithTimeout(ctx, 5*time.Second)
				server := grpcomni.NewManagementServer(authorized, nil, zap.NewNop(), true, noBackend{}, noBackend{},
					grpcomni.WithAuditLogger(&auditLogAccessAuditor{}), grpcomni.WithLogHandler(logHandler))
				result := &yaml.Node{Kind: yaml.ScalarNode, Value: rpcOutcome(handlers[name](server, ctx, call.request))}

				cancel()

				if len(calls) == 1 {
					outcomes = result

					break
				}

				outcomes.Content = append(outcomes.Content, &yaml.Node{Kind: yaml.ScalarNode, Value: call.name}, result)
			}

			rpcs.Content = append(rpcs.Content, &yaml.Node{Kind: yaml.ScalarNode, Value: name}, outcomes)
		}

		rpcs.HeadComment = fmt.Sprintf(rpcGoldenHeader, subject.Name, subject.Description)

		var buf bytes.Buffer

		encoder := yaml.NewEncoder(&buf)
		encoder.SetIndent(2)

		require.NoError(t, encoder.Encode(rpcs))
		require.NoError(t, encoder.Close())

		files[subject.Name+".yaml"] = buf.Bytes()
	}

	authztest.CompareGoldenFiles(t, filepath.Join("testdata", "authorization"), files)
}

// rpcOutcome returns what the access check of a handler decided, as it is written in the golden files.
func rpcOutcome(err error) string {
	switch status.Code(err) { //nolint:exhaustive
	case codes.Unauthenticated:
		return "unauthenticated"
	case codes.PermissionDenied:
		return "denied"
	default:
		return "allowed"
	}
}

// requestStream is the stream of a server-streaming RPC, which gives the handler its request and drops the responses.
type requestStream struct {
	grpc.ServerStream

	ctx     context.Context //nolint:containedctx
	request proto.Message
}

func (s *requestStream) Context() context.Context {
	return s.ctx
}

func (s *requestStream) RecvMsg(m any) error {
	proto.Merge(m.(proto.Message), s.request) //nolint:forcetypeassert,errcheck

	return nil
}

func (s *requestStream) SendMsg(any) error {
	return nil
}
