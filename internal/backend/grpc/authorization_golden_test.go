const rpcGoldenHeader = `What %s can do through the management API.
%s

Generated by TestRPCAuthorizationGolden. Rewrite with:

  go test ./internal/backend/grpc -run TestRPCAuthorizationGolden -update

An RPC with more than one call lists them by what the request is for.

A call is "unauthenticated" or "denied" when the access check refused it, and "allowed" when the check let it through.
What happens to an allowed call after the check is not recorded: the server has no Talos, Kubernetes or image factory
behind it, and most of the clusters and machines of the requests do not exist, so most of the calls fail there.

The break-glass configs are enabled on the server. Without that, every break-glass call is refused.`

// rpcCall is a call to an RPC of the management API.
type rpcCall struct {
	request proto.Message
	// name says in the golden file what the request is for, e.g., "cluster-a". An RPC with a single call does not need it.
	name string
	// cluster is the cluster the request is for, sent in the metadata the way the clients send it.
	cluster string
}

func onClusters(request proto.Message) []rpcCall {
	return []rpcCall{
		{name: authztest.ClusterA, cluster: authztest.ClusterA, request: request},
		{name: authztest.ClusterB, cluster: authztest.ClusterB, request: request},
	}
}

func onMachines[T proto.Message](request func(machineID string) T) []rpcCall {
	return []rpcCall{
		{name: "a machine in cluster-a", request: request(authztest.MemberMachine)},
		{name: "a machine in cluster-b", request: request(authztest.OtherMachine)},
		{name: "a machine in no cluster", request: request(authztest.FreeMachine)},
	}
}

func once(request proto.Message) []rpcCall {
	return []rpcCall{{request: request}}
}

