const talosGoldenHeader = `What %s can do on the Talos API of a machine through Omni.
%s

Generated by TestTalosAuthorizationGolden. Rewrite with:

  go test ./internal/backend/grpc/router -run TestTalosAuthorizationGolden -update

Omni forwards a request to the Talos API with a Talos role on it. A call shows this role, or "unauthenticated" or
"denied" when Omni refuses the request. The requests are a read (Hostname), the read of a file (Read), which needs more
on Talos 1.12 and later, and a request which destroys data (BlockDeviceWipe). The machines run Talos 1.12.

A node which cannot be resolved is "reported" when the caller is told that the node is not found. Otherwise the caller
gets the refusal of a request it has no access for, "unauthenticated" or "denied". Only the role of the user counts
here, also when the request is for a cluster.`

// machineResolver resolves the ID of a machine to the machine, using its ID as the key. It resolves no other node.
type machineResolver map[string]dns.Info

func (r machineResolver) Resolve(_, node string) (dns.Info, error) {
	info, ok := r[node]
	if !ok {
		return dns.Info{}, dns.ErrNotFound
	}

	return info, nil
}

// signedInAlready stands in for the signature verifier, as the caller in the context is signed in already.
func signedInAlready(ctx context.Context, req any, _ *grpc.UnaryServerInfo, handler grpc.UnaryHandler) (any, error) {
	return handler(ctx, req)
}

// TestTalosAuthorizationGolden records the Talos role every subject gets on the requests to the Talos API of a machine,
// and fails on any difference from the golden files.
func TestTalosAuthorizationGolden(t *testing.T) {
	keys := authztest.GenerateKeys(t)
	st := state.WrapCore(inmem.NewState())

	authztest.Seed(t, st, keys)

	requests := []struct {
		name   string
		method string
	}{
		{"read", machine.MachineService_Hostname_FullMethodName},
		{"read a file", machine.MachineService_Read_FullMethodName},
		{"destroy data", storage.StorageService_BlockDeviceWipe_FullMethodName},
	}

	targets := []struct {
		name    string
		machine string
		cluster string
	}{
		{"a machine in cluster-a", authztest.MemberMachine, authztest.ClusterA},
		{"a machine in cluster-b", authztest.OtherMachine, authztest.ClusterB},
		{"a machine in no cluster", authztest.FreeMachine, ""},
	}

	secretsData, err := testsecrets.BundleData(nil)
	require.NoError(t, err)

	resolver := machineResolver{}

	for _, target := range targets {
		resolver[target.machine] = dns.Info{Cluster: target.cluster, ID: target.machine, TalosVersion: "1.12.0", ManagementEndpoint: "127.0.0.1"}

		// the router needs the secrets of a cluster for the connection to its machines, which is never opened here
		if target.cluster != "" {
			clusterSecrets := omni.NewClusterSecrets(target.cluster)
			clusterSecrets.TypedSpec().Value.Data = secretsData

			require.NoError(t, st.Create(t.Context(), clusterSecrets))
		}
	}

	talosRouter, err := router.NewRouter(memconn.NewTransport("golden"), st, resolver, nil, signedInAlready)
	require.NoError(t, err)

	// talosRequest returns the context of a request of the caller to the Talos API of the node
	talosRequest := func(ctx context.Context, node, cluster string) context.Context {
		md := metadata.Pairs("node", node, message.RuntimeHeaderKey, common.Runtime_Talos.String())
		if cluster != "" {
			md.Set("cluster", cluster)
		}

		return metadata.NewIncomingContext(ctx, md)
	}

	authztest.CompareGolden(t, talosGoldenHeader, func(subject authztest.Subject, outcomes *authztest.Outcomes) {
		ctx := authztest.SignIn(t, st, keys, subject)

		for _, target := range targets {
			// the request has no cluster, so the router takes the cluster of the machine
			reqCtx := talosRequest(ctx, target.machine, "")

			var roles authztest.Outcomes

			for _, request := range requests {
				_, backends, err := talosRouter.Director(reqCtx, request.method)
				require.NoError(t, err)

				outCtx, _, err := backends[0].GetConnection(reqCtx, request.method)

				roles.Add(request.name, talosRole(t, outCtx, err))
			}

			outcomes.AddGroup(target.name, &roles)
		}

		for _, request := range []struct {
			name    string
			cluster string
		}{
			{name: "a node which cannot be resolved"},
			{name: "a node of cluster-a which cannot be resolved", cluster: authztest.ClusterA},
		} {
			_, _, err := talosRouter.Director(talosRequest(ctx, "missing", request.cluster), machine.MachineService_Hostname_FullMethodName)

			if status.Code(err) == codes.NotFound {
				outcomes.Add(request.name, "reported")

				continue
			}

			require.Error(t, err)
			outcomes.Add(request.name, authztest.Outcome(t, err))
		}
	})
}

// talosRole returns the Talos role on a request which Omni forwards, or why Omni refused the request.
func talosRole(t *testing.T, ctx context.Context, err error) string {
	if err != nil {
		return authztest.Outcome(t, err)
	}

	md, _ := metadata.FromOutgoingContext(ctx)

	return strings.Join(md.Get(constants.APIAuthzRoleMetadataKey), ", ")
}
