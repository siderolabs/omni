package workloadproxy_test

import (
	"encoding/base64"
	"testing"

	"github.com/cosi-project/runtime/pkg/state"
	"github.com/cosi-project/runtime/pkg/state/impl/inmem"
	"github.com/stretchr/testify/require"

	"github.com/siderolabs/omni/internal/backend/services/workloadproxy"
	"github.com/siderolabs/omni/internal/pkg/authz/authztest"
)

const authorizationGoldenHeader = `Which exposed services %s can reach through the workload proxy.
%s

Generated by TestAuthorizationGolden. Rewrite with:

  go test ./internal/backend/services/workloadproxy -run TestAuthorizationGolden -update

A request to an exposed service of a cluster carries the ID of a public key of the user and the signature of this ID,
in cookies. A call is "allowed" when the access validator of the workload proxy accepts them for the cluster, and
"denied" on any error of it, as the proxy sends every refused request to the forbidden page.

The anonymous subject has no key. It is "denied" by the validator here, while the proxy sends a request without the
cookies to the login page before it asks the validator.`

// TestAuthorizationGolden records which subjects can reach the exposed services of a cluster,
// and fails on any difference from the golden files.
func TestAuthorizationGolden(t *testing.T) {
	keys := authztest.GenerateKeys(t)
	st := state.WrapCore(inmem.NewState())

	authztest.Seed(t, st, keys)

	authztest.CompareGolden(t, authorizationGoldenHeader, func(subject authztest.Subject, outcomes *authztest.Outcomes) {
		validator, err := workloadproxy.NewSignatureAccessValidator(authztest.Authenticator(st, subject), st)
		require.NoError(t, err)

		keyID := keys.ID(subject)
		signature := base64.StdEncoding.EncodeToString(keys.Sign(t, subject, []byte(keyID)))

		wrongSignature := base64.StdEncoding.EncodeToString(keys.Sign(t, subject, []byte("other")))

		outcome := func(signature, cluster string) string {
			if err = validator.ValidateAccess(t.Context(), keyID, signature, cluster); err != nil {
				return "denied"
			}

			return "allowed"
		}

		for _, cluster := range []string{authztest.ClusterA, authztest.ClusterB} {
			outcomes.Add(cluster, outcome(signature, cluster))
			outcomes.Add(cluster+" with a wrong signature", outcome(wrongSignature, cluster))
		}
	})
}
